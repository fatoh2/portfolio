// PROTOTYPE, throwaway. Writes scope-data.js for h-scope.html from the site's own content, so the preview
// shows real copy, links and statuses in three languages. Run from the repo root:
//   node --experimental-strip-types design/concepts/2026-11/previews/build-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const at = f => new URL(f, import.meta.url);
const p = await import(at('../../../../src/content/portfolio.ts').href);
const u = await import(at('../../../../src/content/ui.ts').href);
const now = Object.fromEntries(JSON.parse(readFileSync(at('../../../../src/content/now.json'), 'utf8')).map(n => [n.slug, n]));
// every project has a phone capture; all but one also have a desktop one
const shots = x => ({ tall: x.media.find(m => m.height > m.width)?.src ?? null, wide: x.media.find(m => m.width > m.height)?.src ?? null });
const kind = (x, k) => x.links.filter(l => l.kind === k).map(l => ({ href: l.href, label: l.label }));
const cards = [
  ...p.projects.map(x => ({
    slug: x.slug, title: x.title, status: x.status, cat: x.category, sum: x.summary, img: x.media[0].src, ...shots(x),
    live: kind(x, 'live')[0] ?? null, embeds: x.media.filter(m => m.embed).map(m => m.embed), apks: kind(x, 'download'), page: true, now: now[x.slug] ?? null,
  })),
  // Saqroon is a different shape in the content file and has no case page
  (f => ({
    slug: f.slug, title: f.title, status: f.status, cat: f.category, sum: f.summary, img: f.media[0].src, ...shots(f),
    live: { href: f.website, label: f.websiteLabel }, apks: f.builds.map(b => ({ href: b.apkUrl, label: b.label })),
    page: false, note: f.downloadNote, now: now[f.slug] ?? null,
  }))(p.focusQuest),
];
const site = {
  ui: Object.fromEntries(p.locales.map(l => [l, u.getDictionary(l)])),
  status: u.statusLabels, services: p.services, profile: p.profile, cards,
};
writeFileSync(at('scope-data.js'), `/* PROTOTYPE, throwaway. Generated by build-data.mjs from src/content. Do not edit. */\nconst SITE = ${JSON.stringify(site, null, 1)};\n`);
console.log(cards.length, 'cards;', cards.filter(c => c.status === 'live-product').length, 'live;', cards.filter(c => c.apks.length).length, 'installable');
